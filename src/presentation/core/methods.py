from folium.plugins import MarkerCluster

@ht.timer
def make_streamlit_electric_Charging_Stations_Map_with_Search_and_Clustering(dfr):
    """Displays a map with Electric Charging Stations as clustered markers and a search bar for filtering by postal code."""

    dframe = dfr.copy()

    # Streamlit app
    st.title('Map of Electric Charging Stations')

    # Add a text input for postal code search
    search_plz = st.text_input("Enter Postal Code (PLZ) to filter:", "")

    # Filter the dataframe by the entered postal code
    if search_plz:
        filtered_dframe = dframe[dframe['PLZ'].astype(str).str.startswith(search_plz)]
    else:
        filtered_dframe = dframe

    if filtered_dframe.empty:
        st.warning(f"No charging stations found for postal code: {search_plz}")
        return

    # Create a Folium map
    m = folium.Map(location=[52.52, 13.40], zoom_start=10)

    # Use MarkerCluster to cluster markers
    marker_cluster = marker_cluster = MarkerCluster(
        disableClusteringAtZoom=14,  # Stop clustering beyond zoom level 4
        maxClusterRadius=50         # Increase cluster radius to group markers more aggressively
    ).add_to(m)

    # Add markers for each charging station in the filtered dataframe
    for idx, row in filtered_dframe.iterrows():
        # Extract latitude and longitude
        lat = float(row['Breitengrad'])
        lon = float(row['Längengrad'])
        tooltip = f"PLZ: {row['PLZ']}, KW: {row['KW']}"

        # Add marker to the cluster
        folium.Marker(location=[lat, lon], tooltip=tooltip).add_to(marker_cluster)

    # Display the map in Streamlit
    folium_static(m, width=800, height=600)

    # Display the filtered data as a table
    st.subheader("Filtered Charging Stations")
    st.dataframe(filtered_dframe[['PLZ', 'KW', 'Breitengrad', 'Längengrad']])
